function wrap(t, w) {
  const parts = t.split(/(<[^>]*>)/);
  for (let j = 0; j < parts.length; j++) {
    if (parts[j].startsWith('<')) continue;
    const at = parts[j].indexOf(w); if (at < 0) continue;
    parts[j] = `${parts[j].slice(0, at)}<b class="kw">${w}</b>${parts[j].slice(at + w.length)}`;
    return parts.join('');
  }
  return null;
}

export function keyBold(s, id, lang, i) {
  const k = K[`${id}|${lang}|${i}`];
  if (k) { const r = wrap(s, k); if (r) return r; }
  const m = /^([^:<\[]{2,40}?):\s/.exec(s);
  if (m && m[1].trim().split(/\s+/).length <= 5) return `<b class="kw">${m[1]}</b>${s.slice(m[1].length)}`;
  return s;
}

export function whyBold(s, id, lang) {
  let r = s;
  for (const w of W[`${id}|${lang}`] ?? []) r = wrap(r, w) ?? r;
  return r;
}
